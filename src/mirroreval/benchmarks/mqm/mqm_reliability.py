"""
MQM Reliability
===============
Per-language evidence on how well BLEU, chrF and COMET track human judgment,
taken from AmanaMT v2 (Thompson and Ringger; revision of ACL Anthology
2026.wmt-main.42; code: https://github.com/byu-matrix-lab/amana-mt).

The numbers live in ``amanamt_v2_reliability.json``, which is generated by
``scripts/export_mirror_eval_reliability.py`` in the amana-mt repository from
its result files. Do not edit the JSON by hand; regenerate and copy it.

This benchmark translates English into each target language, so the evidence
that applies most directly is an en->X measurement against human labels.
Each language is tagged with one of three evidence levels:

  - "direct_en_to_x": human labels (expert MQM or DA) on en->X translations.
  - "indirect":       human labels, but only for X->en (or pooled directions).
  - "none":           only synthetic (LLM) labels, or labels AmanaMT v2 found
                      uninformative. No reliability claim should be made.

AmanaMT v2's main caveat applies throughout: metric--human correlation depends
on which human labels it is measured against (protocol, direction, year), so
these are descriptive values, not a property of the language alone.
"""

import json
from functools import lru_cache
from importlib import resources
from typing import Any

EVIDENCE_LEVELS = ("direct_en_to_x", "indirect", "none")


@lru_cache(maxsize=1)
def load_reliability() -> dict[str, Any]:
    """Load the packaged AmanaMT v2 reliability table."""
    text = (
        resources.files("mirroreval.benchmarks.mqm")
        .joinpath("amanamt_v2_reliability.json")
        .read_text(encoding="utf-8")
    )
    return json.loads(text)


def build_reliability_section(langs: list[str], metrics: list[str]) -> dict[str, Any]:
    """Per-language reliability evidence for the evaluated languages and metrics."""
    table = load_reliability()
    section: dict[str, Any] = {
        "source": table["source"],
        "amana_mt_commit": table["amana_mt_commit"],
        "statistic": table["statistic"],
        "languages": {},
    }
    for lang in langs:
        entry = table["languages"].get(lang)
        if entry is None:
            section["languages"][lang] = {
                "evidence": "none",
                "note": "Not covered by AmanaMT v2.",
            }
            continue
        out = {k: entry[k] for k in ("evidence", "label_type", "language_pairs", "directions")}
        out["metrics"] = {m: entry["metrics"][m] for m in metrics if m in entry["metrics"]}
        if "note" in entry:
            out["note"] = entry["note"]
        section["languages"][lang] = out
    return section


def _best_en_to_x(entry: dict[str, Any], metrics: list[str]) -> str | None:
    scored = {
        m: entry["metrics"][m]["en_to_x"]["spearman_r"]
        for m in metrics
        if m in entry["metrics"] and "en_to_x" in entry["metrics"][m]
    }
    return max(scored, key=scored.get) if scored else None


def recommendation(langs: list[str], metrics: list[str]) -> str:
    """Plain-English summary that states only what the evidence supports."""
    table = load_reliability()["languages"]
    by_level: dict[str, list[str]] = {lvl: [] for lvl in EVIDENCE_LEVELS}
    best: dict[str, list[str]] = {}
    for lang in langs:
        entry = table.get(lang)
        level = entry["evidence"] if entry else "none"
        by_level[level].append(lang)
        if level == "direct_en_to_x":
            b = _best_en_to_x(entry, metrics)
            if b:
                best.setdefault(b, []).append(lang)

    parts = []
    if best:
        parts.append(
            "Where AmanaMT v2 measured en->X reliability against human labels, the "
            "highest-correlating metric among those run was: "
            + "; ".join(f"{m} ({', '.join(ls)})" for m, ls in sorted(best.items()))
            + "."
        )
    if by_level["indirect"]:
        parts.append(
            "For " + ", ".join(by_level["indirect"]) + " the only human evidence is "
            "X->en, which may not transfer to en->X."
        )
    if by_level["none"]:
        parts.append(
            "For " + ", ".join(by_level["none"]) + " there is no reliable human "
            "evidence (synthetic labels or uninformative labels); treat all metric "
            "scores there as unvalidated."
        )
    parts.append(
        "Reliability depends on the human labels it is measured against "
        "(AmanaMT v2), and stronger metrics than these three exist (e.g. MetricX-24 "
        "had the highest mean correlation in AmanaMT v2)."
    )
    return " ".join(parts)
